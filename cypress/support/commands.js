Cypress.Commands.add('visitWithTimeout', (url = '/') => { 
  cy.visit(url, {
    failOnStatusCode: false,
    timeout: 60000,
    loadTimeout: 0,
    onBeforeLoad(win) { //это все потому что сайт в постоянной подгрузке
      setTimeout(() => win.stop(), 5000);
    },
  });
});
